"""The product on dev as a test account, through mvp's eval_system client in a child process
(evalsystem_child.py). Session: the account's password (``accounts.tsv``: email<TAB>password)
signed in once through evalsystem_mint.py and cached under ``session_cache/<env>-cookies.json``.
Needs ``uv`` and a checkout of mvp at ``mvp_dir``; the accounts yaml eval_system wants is
generated from accounts.tsv under the data root."""
from __future__ import annotations

import fcntl
import json
import os
import shutil
import subprocess
import threading
from pathlib import Path

from behavioreval.core.config import Config, column, load_accounts, secrets
from behavioreval.core.endpoint import AssistantTurn

HERE = Path(__file__).resolve().parent
CHILD, MINT = HERE / "evalsystem_child.py", HERE / "evalsystem_mint.py"


def child_env(cfg: Config, environ=None) -> dict[str, str]:
    environ = os.environ if environ is None else environ
    env = dict(environ)
    env.update(secrets(cfg, environ))
    env["EVAL_DD_OPTIONAL"] = "1"
    for k in ("GOOGLE_REFRESH_TOKEN", "EVAL_SESSION_COOKIE", "EVAL_USER_PASSWORD", "BEHAVIOREVAL_CACHED_SESSION"):
        env.pop(k, None)
    missing = [k for k in ("CF_ACCESS_CLIENT_ID", "CF_ACCESS_CLIENT_SECRET") if not env.get(k)]
    if missing:
        raise ValueError(f"eval_system needs {', '.join(missing)} (environment or {cfg.secrets_file})")
    return env


def accounts_yaml(cfg: Config, accounts: dict[str, str]) -> Path:
    """The accounts file eval_system's pool reads, written from accounts.tsv (emails only; passwords go through the env)."""
    path = cfg.data_root / f"accounts-{cfg.env}.yaml"
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# generated by behavioreval from accounts.tsv; emails only", "accounts:"]
    for email in accounts:
        lines += [f"  - email: {email}", "    surfaces: ['api']", f"    environments: ['{cfg.env}']", "    provides: []"]
    text = "\n".join(lines) + "\n"
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        path.write_text(text, encoding="utf-8")
    return path


def cache_file(cfg: Config) -> Path:
    return cfg.session_cache / f"{cfg.env}-cookies.json"


def cached_session(cfg: Config, email: str) -> str:
    f = cache_file(cfg)
    try:
        return json.loads(f.read_text(encoding="utf-8")).get(email, "") if f.exists() else ""
    except ValueError:
        return ""


def store_session(cfg: Config, email: str, cookie: str) -> None:
    f = cache_file(cfg)
    f.parent.mkdir(parents=True, exist_ok=True)
    with open(f.with_suffix(".lock"), "w") as lk:
        fcntl.flock(lk, fcntl.LOCK_EX)
        try:
            d = json.loads(f.read_text(encoding="utf-8")) if f.exists() else {}
        except ValueError:
            d = {}
        d[email] = cookie
        f.write_text(json.dumps(d, indent=1), encoding="utf-8")
        os.chmod(f, 0o600)


def check(cfg: Config) -> list[tuple[str, bool, str]]:
    """(what, ok, detail) for everything the evalsystem endpoint needs; nothing secret in the details."""
    sec = secrets(cfg)
    accounts = load_accounts(cfg.accounts_file)
    out = [("python3", True, "running"),
           ("uv on PATH", bool(shutil.which("uv")), shutil.which("uv") or "install: https://docs.astral.sh/uv/"),
           ("mvp checkout", cfg.eval_dir.exists(), str(cfg.eval_dir)),
           ("Cloudflare Access token", bool(sec.get("CF_ACCESS_CLIENT_ID") and sec.get("CF_ACCESS_CLIENT_SECRET")), f"CF_ACCESS_CLIENT_ID / _SECRET in {cfg.secrets_file.name}"),
           ("OpenRouter key", bool(sec.get("OPENROUTER_API_KEY")), f"OPENROUTER_API_KEY in {cfg.secrets_file.name}"),
           ("accounts", bool(accounts), f"{len(accounts)} in {cfg.accounts_file.name}" if accounts else f"copy accounts.example.tsv to {cfg.accounts_file.name}"),
           ("cached sessions", True, f"{len([e for e in accounts if cached_session(cfg, e)])} of {len(accounts)} signed in before")]
    return out


def mint_session(cfg: Config, email: str, out=print) -> str:
    accounts = load_accounts(cfg.accounts_file)
    if email not in accounts:
        raise ValueError(f"no password for {email} in {cfg.accounts_file.name}")
    env = child_env(cfg)
    env["EVAL_USER_PASSWORD"] = accounts[email]
    cached = cached_session(cfg, email)
    if cached:
        env["BEHAVIOREVAL_CACHED_SESSION"] = cached
    cmd = ["uv", "run", "python", str(MINT), "--email", email, "--accounts", str(accounts_yaml(cfg, accounts)), "--env", cfg.env]
    try:
        r = subprocess.run(cmd, cwd=cfg.eval_dir, env=env, capture_output=True, text=True, timeout=180)
    except (subprocess.TimeoutExpired, OSError) as exc:
        raise RuntimeError(f"sign-in for {email} failed: {type(exc).__name__}") from None
    if r.returncode != 0:
        why = ((r.stderr or "").strip().splitlines() or ["no stderr"])[-1]
        raise RuntimeError(f"sign-in for {email} failed (rc={r.returncode}): {why[:200]}")
    lines = [l.strip() for l in (r.stdout or "").splitlines() if l.strip()]
    if not lines:
        raise RuntimeError(f"sign-in for {email} printed no session")
    cookie = lines[-1]
    if cookie != cached:
        store_session(cfg, email, cookie)
        out(f"  signed in {email} (session cached)")
    return cookie


class EvalSystemEndpoint:
    def __init__(self, cfg: Config, out=print, popen=subprocess.Popen, mint=mint_session, environ=None):
        self.cfg, self.out, self.popen, self.mint, self.environ = cfg, out, popen, mint, environ
        self.proc = None
        self.trajectory_path: Path | None = None
        self.note = ""
        self.n = 0

    def _line(self, deadline_s: float) -> dict:
        box: dict = {}

        def reader():
            box["line"] = self.proc.stdout.readline()
        t = threading.Thread(target=reader, daemon=True)
        t.start()
        t.join(deadline_s)
        if t.is_alive():
            raise TimeoutError(f"the eval_system child said nothing in {deadline_s:.0f} s")
        line = (box.get("line") or "").strip()
        if not line:
            err = ""
            try:
                err = (self.proc.stderr.read() or "")[-400:]
            except Exception:
                pass
            raise RuntimeError(f"the eval_system child ended without answering: {err.strip() or 'no stderr'}")
        try:
            return json.loads(line)
        except ValueError:
            raise RuntimeError(f"the eval_system child printed no JSON: {line[:160]!r}") from None

    def open(self, account: str, lane: str, title: str, profile: dict) -> str:
        if not account:
            raise ValueError("the evalsystem endpoint needs an account (accounts.tsv)")
        cookie = self.mint(self.cfg, account, self.out)
        env = child_env(self.cfg, self.environ)
        env["EVAL_SESSION_COOKIE"] = cookie
        self.trajectory_path = self.cfg.data_root / "trajectories" / f"{account.split('@')[0]}-{title.replace(' ', '_').replace('/', '_')[:80]}.json"
        self.trajectory_path.parent.mkdir(parents=True, exist_ok=True)
        label, model, provider = column(self.cfg)
        cmd = ["uv", "run", "python", str(CHILD), "--env", self.cfg.env, "--email", account, "--model", model, "--provider", provider,
               "--title", title, "--timeout", str(self.cfg.turn_timeout_s), "--out", str(self.trajectory_path)]
        if profile:
            cmd += ["--profile", json.dumps(profile, ensure_ascii=False)]
        self.proc = self.popen(cmd, cwd=self.cfg.eval_dir, env=env, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, bufsize=1)
        opened = self._line(240)
        if opened.get("op") != "open":
            raise RuntimeError(f"the eval_system child did not open a conversation: {opened}")
        self.out(f"  {opened.get('note', '')}" + (f"; profile {opened['profile']}" if opened.get("profile") else ""))
        self.note = str(opened.get("note") or "")
        return str(opened.get("conversation_id") or "")

    def turn(self, text: str, timeout_s: float) -> AssistantTurn:
        self.n += 1
        self.proc.stdin.write(json.dumps({"op": "send", "text": text}) + "\n")
        self.proc.stdin.flush()
        ans = self._line(timeout_s + 120)
        if ans.get("op") != "turn":
            raise RuntimeError(f"the eval_system child answered {ans}")
        t = AssistantTurn(reply=str(ans.get("reply") or ""), reason=str(ans.get("reason") or ""),
                          calls=[c for c in ans.get("calls") or [] if isinstance(c, dict)],
                          duration_s=float(ans.get("duration_s") or 0) + float(ans.get("held_s") or 0), error=str(ans.get("error") or ""),
                          note=self.note if self.n == 1 else "")
        if t.error and not t.reason and not t.reply:
            raise TimeoutError(t.error)
        return t

    def close(self) -> None:
        if not self.proc:
            return
        try:
            self.proc.stdin.write(json.dumps({"op": "close"}) + "\n")
            self.proc.stdin.flush()
            self.proc.wait(timeout=60)
        except Exception:
            self.proc.kill()


def create(name: str, cfg: Config, out=print):
    return EvalSystemEndpoint(cfg, out)
